const images = (manifest as { cars: Record<string, CarImage[]> }).cars;

// Which fetched photos to show, cover first, by file name. Cars not listed
// use every photo in fetch order. Interior shots always go last.
const CURATE: Record<string, string[]> = {
  "mercedes-gle-300d-2025": ["1", "3"],
  "ford-endeavour-2021": ["2", "3", "4", "1"],
  "mahindra-xuv700-2022": ["1", "3", "2"],
  "porsche-911-carrera-s-2021": ["2", "1", "3"],
  "porsche-taycan-4s-2023": ["2", "1", "4", "3"],
  "land-rover-defender-110-2023": ["2", "1", "3", "4"],
  "mercedes-s350d-2021": ["1", "2", "3"],
  "maybach-s580-2022": ["3", "1", "2", "4"],
  "rolls-royce-ghost-2019": ["4", "1", "2", "3"],
};

function curated(id: string): CarImage[] {
  const all = images[id] ?? [];
  const name = (img: CarImage) => img.src.split("/").pop()!.replace(".jpg", "");
  const interior = all.filter((img) => name(img).startsWith("interior"));
  const order = CURATE[id];
  const exterior = order
    ? order.map((n) => all.find((img) => name(img) === n)).filter((img): img is CarImage => !!img)
    : all.filter((img) => !name(img).startsWith("interior"));
  return [...exterior, ...interior].map((img) => ({ ...img, src: asset(img.src) }));
}

export interface CarWithImages extends Car {
  images: CarImage[];
}

export const inventory: CarWithImages[] = stock.map((car) => ({ ...car, images: curated(car.id) }));

export const byId = new Map(inventory.map((c) => [c.id, c]));

export function carName(car: Car) {
  return `${car.make} ${car.model}`;
}

export function carTitle(car: Car) {
  return `${car.year} ${car.make} ${car.model} ${car.variant}`;
}

/** Brands with stock counts, most stocked first. */
export const brands = Object.entries(
  inventory.reduce<Record<string, number>>((acc, car) => {
    const brand = car.make.startsWith("Mercedes") ? "Mercedes-Benz" : car.make;
    acc[brand] = (acc[brand] ?? 0) + 1;
    return acc;
  }, {}),
)
  .map(([name, count]) => ({ name, count }))
  .sort((a, b) => b.count - a.count || a.name.localeCompare(b.name));

export function brandOf(car: Car) {
  return car.make.startsWith("Mercedes") ? "Mercedes-Benz" : car.make;
}
